LG109_139_human.data <- Read10X(data.dir = "/athena/ganlab/scratch/lif4001/LG109_engraft/cellranger_reanalyze_human/LG109_139_human/outs/filtered_feature_bc_matrix")
LG109_139_human <- CreateSeuratObject(counts = LG109_139_human.data, min.cells = 3, min.features = 200, project = "LG109_139_human")
LG109_139_human[["Condition"]] = c('4R_P301S_Ctrl')
LG109_139_human[["Sample_Name"]] = c('4R_P301S_Ctrl_4')
LG109_139_human[["percent.mt"]] <- PercentageFeatureSet(LG109_139_human, pattern = "^MT-")
pdf("LG109_139_human_QC_violin_plot.pdf", width=6, height=4)
VlnPlot(LG109_139_human, features = c("nFeature_RNA", "nCount_RNA", "percent.mt"), ncol = 3)
VlnPlot(LG109_139_human, features = c("nFeature_RNA", "nCount_RNA", "percent.mt"), ncol = 3, pt.size = 0)
dev.off()
LG109_139_human <- subset(LG109_139_human, subset = nFeature_RNA > 200 & nFeature_RNA < 7000 & nCount_RNA < 30000 & percent.mt < 5)
LG109_139_human <- NormalizeData(LG109_139_human)
LG109_139_human <- FindVariableFeatures(LG109_139_human, selection.method = "vst", nfeatures = 2000)
all.genes <- rownames(LG109_139_human)
LG109_139_human <- ScaleData(LG109_139_human, features = all.genes)
LG109_139_human <- RunPCA(LG109_139_human, features = VariableFeatures(object = LG109_139_human))
ElbowPlot(LG109_139_human)
LG109_139_human <- FindNeighbors(LG109_139_human, dims = 1:15)
LG109_139_human <- FindClusters(LG109_139_human, resolution = 0.1)
LG109_139_human <- RunUMAP(LG109_139_human, dims = 1:15)
saveRDS(LG109_139_human, file = "LG109_139_human.rds")
#Doublet finder (no ground-truth) - please reference https://github.com/chris-mcginnis-ucsf/DoubletFinder for more information on parameters====
sweep.pbmc <- paramSweep(LG109_139_human,PCs=1:15,sct=FALSE)
sweep.stats_pbmc <- summarizeSweep(sweep.pbmc,GT=FALSE)
bcmvn_pbmc <- find.pK(sweep.stats_pbmc)
pdf("LG109_139_human_ggplot_pK.pdf", width=18, height=6)
ggplot(bcmvn_pbmc, aes(x=pK, y=BCmetric))+geom_bar(stat="identity") #look for pK at the initial peak
dev.off()
